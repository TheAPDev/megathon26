"""Generate supabase/migrations/003_reference_data.sql from data/reference/*.csv (single source of truth)."""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "data" / "reference"
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]


def q(v) -> str:
    if v is None or v == "":
        return "null"
    try:
        float(v)
        return str(v)
    except ValueError:
        return "'" + str(v).replace("'", "''") + "'"


def rows(name):
    with open(REF / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def insert(table, cols, values) -> str:
    body = ",\n".join("(" + ", ".join(v) + ")" for v in values)
    return f"insert into public.{table} ({', '.join(cols)}) values\n{body};\n"


def main() -> None:
    out = ["-- Generated by scripts/export_reference_sql.py from data/reference/*.csv. Do not edit by hand.\n"
           "-- Load into an empty database (first deploy). To refresh, truncate the reference tables first.\n"]
    c = rows("cities.csv")
    out.append("insert into public.cities (city, state, lat, lon, nbc_zone, tier, temps, pv_yield_kwh_per_kwp, price_inr_per_sqft) values\n" +
               ",\n".join(f"({q(r['city'])}, {q(r['state'])}, {r['lat']}, {r['lon']}, {q(r['nbc_zone'])}, {r['tier']}, "
                          f"array[{', '.join(r['t_' + m] for m in MONTHS)}]::real[], {r['pv_yield_kwh_per_kwp']}, {r['price_inr_per_sqft']})" for r in c)
               + "\non conflict (city) do nothing;\n")
    ts = rows("tariff_states.csv")
    cols = list(ts[0].keys())
    out.append(insert("tariff_states", cols, [[q(r[k]) if k != "tod_tariff" else ("true" if r[k] == "yes" else "false") for k in cols] for r in ts]))
    sl = rows("tariff_slabs.csv")
    cols = list(sl[0].keys())
    out.append(insert("tariff_slabs", cols, [[q(r[k]) for k in cols] for r in sl]))
    for name, table in (("emission_factors.csv", "emission_factors"), ("subsidy_rules.csv", "subsidy_rules"),
                        ("finance_products.csv", "finance_products"), ("appliances.csv", "appliances"),
                        ("retrofit_catalogue.csv", "retrofit_catalogue"), ("benchmarks.csv", "benchmarks")):
        rs = rows(name)
        cols = list(rs[0].keys())
        out.append(insert(table, cols, [[q(r[k]) for k in cols] for r in rs]))
    zs = rows("zone_suitability.csv")
    out.append(insert("zone_suitability", ["retrofit_id", "zone", "suitability"],
                      [[q(r["retrofit_id"]), q(z), q(r[z])] for r in zs for z in ("hot_dry", "warm_humid", "composite", "temperate", "cold")]))
    (ROOT / "supabase" / "migrations" / "003_reference_data.sql").write_text("\n".join(out))
    print("wrote 003_reference_data.sql", sum(len(x) for x in out), "bytes")


if __name__ == "__main__":
    main()
